// Designer 21 Nov: the Flak turret call-down lands, shoots at aircraft (not at ground units) and goes after its time;
// the Shield barrier's projector stands with the dome and the dome falls when the projector is destroyed.
const { load, makeRequire } = require("../srcmap.js");
const { SRC, DATA } = load(require("path").join(__dirname, "../../frontline")); const req = makeRequire(SRC);
const data = req("data/load.mjs").loadDataSync((n) => DATA[n]);
const S = req("packages/sim/src/index.js");
const sc = req("packages/sim/fixtures/scenarios/frontline.json"), map = req("packages/sim/fixtures/maps/frontline-3.json");
const sim = S.createScenarioSim(data, sc, map, { seed: 7, difficulty: "normal", players: 1 });
const check = (k, ok, v) => console.log(`CHECK ${ok ? "PASS" : "FAIL"} ${k}${v !== undefined ? " " + JSON.stringify(v) : ""}`);
const find = (id) => { for (let o = 0; o < sim.hi; o++) if (sim.alive[o] && sim.d.typeIds[sim.etype[o]] === id) return o; return -1; };
for (let i = 0; i < 3; i++) sim.step();
const fc = sim.d.raw.constants.frontline.frontlineCalls;
check("the Resupply pod is gone, the new calls are offered", !fc.includes("resupply-pod") && fc.includes("flak-turret") && fc.includes("shield-bubble"), fc);
sim.queueCommanderCall(sim.tick + 1, 1, "flak-turret", 1500, 1500);
for (let k = 0; k < 20 * 8; k++) sim.step();
const ft = find("flak-turret-pod");
check("a Flak turret landed", ft >= 0);
const w = sim.spawnUnit("wasp", 0, 1500 - 200, 1500), ws = sim.idToSlot.get(typeof w === "number" ? w : w.ids[0]);
const l = sim.spawnUnit("lancer", 0, 1500 - 120, 1530), ls = sim.idToSlot.get(typeof l === "number" ? l : l.ids[0]);
for (let k = 0; k < 40; k++) sim.step();
console.log("wasp alt", sim.flyAlt ? sim.flyAlt[ws] : "?", "turret mounts", sim.mCount[ft], sim.d.raw.weapons[sim.mWeapon[ft*req("packages/sim/src/data.js").MAX_MOUNTS]].id);
const wh = sim.hp[ws] + sim.shield[ws], lh = sim.hp[ls] + sim.shield[ls];
for (let k = 0; k < 20 * 8; k++) sim.step();
check("it hits the aircraft", !sim.alive[ws] || sim.hp[ws] + sim.shield[ws] < wh - 300, { before: wh, after: sim.alive[ws] ? sim.hp[ws] + sim.shield[ws] : 0 });
check("and leaves the ground vehicle alone", sim.alive[ls] && sim.hp[ls] + sim.shield[ls] >= lh - 100, { before: lh, after: sim.alive[ls] ? sim.hp[ls] + sim.shield[ls] : 0 });
sim.queueCommanderCall(sim.tick + 1, 1, "shield-bubble", 2200, 900);
for (let k = 0; k < 20 * 5; k++) sim.step();
const sp = find("shield-pod");
const domeUp = () => { sim.fxRefresh && sim.fxRefresh(); return sim.fxDomes.length > 0; };
check("the Shield barrier stands with its projector", sp >= 0 && domeUp());
sim.envDamage(sp, 1e6);
for (let k = 0; k < 10; k++) sim.step();
check("destroying the projector drops the dome", !domeUp());
process.exit(0);
